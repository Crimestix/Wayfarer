/** Symbole der Artikel: die Namen aus LegendKeeper, gezeichnet mit Wayfarers eigenen Symbolen. */
import {
  BookOpen,
  Building2,
  CalendarDays,
  Castle,
  Church,
  CircleAlert,
  Dices,
  FileText,
  Flame,
  Gem,
  Ghost,
  Globe,
  HeartHandshake,
  Hourglass,
  House,
  Infinity as InfinityIcon,
  Map as MapIcon,
  MapPin,
  MoonStar,
  Mountain,
  Orbit,
  Pickaxe,
  Sailboat,
  ScrollText,
  Skull,
  Sparkles,
  Sprout,
  Sun,
  TreePalm,
  Trees,
  User,
  Users,
  WandSparkles,
  type LucideIcon,
} from 'lucide-react';

const RULES: [RegExp, LucideIcon][] = [
  [/^(users|people|user-group|family)/, Users],
  [/^(user|person|child)/, User],
  [/^(map-pin|location)/, MapPin],
  [/^map/, MapIcon],
  [/^(city|building)/, Building2],
  [/^house/, House],
  [/^(dungeon|castle|fort|tower)/, Castle],
  [/^(place-of-worship|church)/, Church],
  [/^(scroll)/, ScrollText],
  [/^book/, BookOpen],
  [/^calendar/, CalendarDays],
  [/^(gem|ring)/, Gem],
  [/^(star-and-crescent|moon)/, MoonStar],
  [/^(planet|galaxy|comet)/, Orbit],
  [/^(earth|globe)/, Globe],
  [/^island/, TreePalm],
  [/^mountain/, Mountain],
  [/^(tree|forest)/, Trees],
  [/^sparkle/, Sparkles],
  [/^hands-holding/, HeartHandshake],
  [/^hourglass/, Hourglass],
  [/^(hat-wizard|wand)/, WandSparkles],
  [/^dice/, Dices],
  [/^exclamation/, CircleAlert],
  [/^seedling/, Sprout],
  [/^skull/, Skull],
  [/^(sailboat|ship)/, Sailboat],
  [/^pickaxe/, Pickaxe],
  [/^infinity/, InfinityIcon],
  [/^sun/, Sun],
  [/^(alien|ghost)/, Ghost],
  [/^(dragon|fire)/, Flame],
];

export function ArticleIcon({ icon, size }: { icon: string; size?: number }) {
  const Icon = RULES.find(([rule]) => rule.test(icon))?.[1] ?? FileText;
  return <Icon width={size} height={size} aria-hidden />;
}
